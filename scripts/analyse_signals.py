#!/usr/bin/env python3
"""
Ollama Momentum & Exit Signal Auditor.
Audits all active positions against technical momentum signals (RSI, MACD, Volume ratios, Chandelier exits).
Highlights stocks breaking below stops, flashing divergences, or requiring immediate trims.
"""

import argparse
import json

from ollama_common import (
    get_db_connection,
    resolve_db_path,
    resolve_fallback_endpoint,
    resolve_fallback_model,
    resolve_ollama_endpoint,
    resolve_ollama_model,
    stream_ollama,
)


def extract_signals_data(db_path: str) -> dict:
    conn = get_db_connection(db_path)
    cursor = conn.cursor()

    # 1. Latest actions generated by algo
    cursor.execute("""
        SELECT a.stock_code, a.action, a.rationale, a.timestamp,
               h.quantity, h.average_price, h.current_price,
               (CAST(h.quantity AS REAL) * CAST(h.current_price AS REAL)) as cur_val,
               ((CAST(h.current_price AS REAL) - CAST(h.average_price AS REAL)) / CAST(h.average_price AS REAL) * 100) as pnl_pct
        FROM stock_actions a
        LEFT JOIN holdings_snapshot h ON a.stock_code = h.stock_code
        WHERE a.timestamp = (SELECT MAX(timestamp) FROM stock_actions)
        ORDER BY cur_val DESC
    """)
    action_rows = cursor.fetchall()

    sell_actions = []
    trim_actions = []
    buy_hold_actions = []

    for r in action_rows:
        act = (r["action"] or "").upper()
        item = {
            "stock_code": r["stock_code"],
            "action": r["action"],
            "rationale": r["rationale"],
            "current_value": round(float(r["cur_val"] or 0), 2),
            "pnl_pct": round(float(r["pnl_pct"] or 0), 2) if r["pnl_pct"] is not None else None,
        }
        if "SELL" in act or "STOP" in act:
            sell_actions.append(item)
        elif "TRIM" in act or "PAUSE" in act or "PROFIT" in act:
            trim_actions.append(item)
        else:
            buy_hold_actions.append(item)

    # 2. Latest technical indicator readings for portfolio holdings
    cursor.execute("""
        SELECT s.stock_code, s.rsi14, s.macd_line, s.macd_signal,
               s.pct_from_52w_high, s.volume_ratio_20d, s.composite_score,
               h.current_price, st.stage, st.slope
        FROM signals s
        JOIN holdings_snapshot h ON s.stock_code = h.stock_code
        LEFT JOIN (
            SELECT stock_code, stage, slope
            FROM stage_history s1
            JOIN (SELECT stock_code as sc, MAX(date) as md FROM stage_history GROUP BY stock_code) s2
            ON s1.stock_code = s2.sc AND s1.date = s2.md
        ) st ON s.stock_code = st.stock_code
        WHERE s.timestamp = (SELECT MAX(timestamp) FROM signals)
        ORDER BY CAST(s.composite_score AS REAL) ASC
    """)
    sig_rows = cursor.fetchall()

    overbought = []
    oversold = []
    weak_momentum = []

    for r in sig_rows:
        rsi = float(r["rsi14"] or 50)
        score = float(r["composite_score"] or 50)
        item = {
            "stock_code": r["stock_code"],
            "rsi14": round(rsi, 1),
            "composite_score": round(score, 1),
            "pct_from_52w_high": round(float(r["pct_from_52w_high"] or 0), 1),
            "volume_ratio_20d": round(float(r["volume_ratio_20d"] or 1), 2),
            "stage": r["stage"],
            "slope": round(float(r["slope"]), 4) if r["slope"] is not None else None,
        }
        if rsi >= 70:
            overbought.append(item)
        elif rsi <= 35:
            oversold.append(item)
        if score < 40:
            weak_momentum.append(item)

    conn.close()

    return {
        "summary": {
            "sell_or_stop_count": len(sell_actions),
            "trim_or_pause_count": len(trim_actions),
            "buy_or_hold_count": len(buy_hold_actions),
            "overbought_count": len(overbought),
            "oversold_count": len(oversold),
            "weak_momentum_count": len(weak_momentum),
        },
        "critical_sell_signals": sell_actions,
        "trim_warnings": trim_actions,
        "weak_momentum_holdings": weak_momentum[:8],
        "overbought_holdings": overbought,
        "oversold_holdings": oversold,
    }


def main():
    parser = argparse.ArgumentParser(description="Audit momentum and exit signals with Ollama")
    parser.add_argument("--db", default=resolve_db_path(), help="Path to SQLite database")
    parser.add_argument("--ollama-url", default=resolve_ollama_endpoint(), help="Primary Ollama base URL")
    parser.add_argument("--model", default=resolve_ollama_model(), help="Primary Ollama model name")
    parser.add_argument("--fallback-url", default=resolve_fallback_endpoint(), help="Fallback Ollama base URL")
    parser.add_argument("--fallback-model", default=resolve_fallback_model(), help="Fallback Ollama model name")
    parser.add_argument("--dry-run", action="store_true", help="Print extracted data and exit")
    args = parser.parse_args()

    data = extract_signals_data(args.db)

    if args.dry_run:
        print(json.dumps(data, indent=2))
        return

    system_prompt = (
        "You are an expert quantitative technical trader and disciplined risk manager. "
        "Your priority is strict capital preservation, honoring trailing stop-losses, and identifying overextended momentum."
    )

    prompt = f"""
Analyze the following active technical signals and algorithmic exit recommendations for PortfolioPi:

SIGNALS & RISK EXPOSURE DATA:
```json
{json.dumps(data, indent=2)}
```

Deliver a concise, urgent trading report with these sections:
1. **Critical Stop-Loss / Sell Triggers**:
   - Assess all items flagged under `critical_sell_signals` (e.g. Chandelier exit breaches, Stage 4 breaks).
   - Rate the urgency (HIGH/MEDIUM) of exiting each flagged position.

2. **Profit-Taking & Trim Candidates**:
   - Review stocks under `trim_warnings` and `overbought_holdings` (RSI > 70, extended above moving averages).
   - Specify whether to execute a trailing stop or lock partial profits.

3. **Oversold Rebound vs Value Traps**:
   - Evaluate `oversold_holdings` and `weak_momentum_holdings`. Identify which are falling knives/value traps vs potential accumulation candidates.

4. **Actionable Trading Checklist**:
   - Provide an immediate 3-step execution plan for Monday's open.
"""

    print(
        f"[*] Auditing momentum signals via Ollama (Primary: {args.model} @ {args.ollama_url} | Fallback: {args.fallback_model} @ {args.fallback_url})...\n"
        + "=" * 60
        + "\n"
    )
    stream_ollama(
        prompt,
        system_prompt=system_prompt,
        base_url=args.ollama_url,
        model=args.model,
        fallback_url=args.fallback_url,
        fallback_model=args.fallback_model,
    )

    print("\n" + "=" * 60)


if __name__ == "__main__":
    main()
